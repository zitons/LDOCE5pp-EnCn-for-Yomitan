class Parser:
    def __init__(self):
        self.unknown = Counter()

    @staticmethod
    def _balanced(html, open_start):
        """Inner HTML of the element whose '<' is at open_start."""
        m = re.match(r"<(\w+)", html[open_start:])
        if not m:
            return None
        tag = m.group(1).lower()
        gt = html.find(">", open_start)
        if gt < 0:
            return None
        body_start = gt + 1
        depth = 1
        for tok in re.finditer(r"<(/?)(\w+)[^>]*?(/?)>", html[body_start:]):
            closing, name, selfclose = (tok.group(1), tok.group(2).lower(),
                                        tok.group(3))
            if name != tag or selfclose:
                continue
            if closing:
                depth -= 1
                if depth == 0:
                    return html[body_start:body_start + tok.start()]
            else:
                depth += 1
        return html[body_start:]

    def _cls_inner(self, html, cls):
        for m in re.finditer(r'<(\w+)[^>]*\bclass="([^"]*)"[^>]*>', html, re.I):
            if cls in m.group(2).split():
                return self._balanced(html, m.start())
        return None

    def _cls_text(self, html, cls):
        inner = self._cls_inner(html, cls)
        return strip_tags(inner) if inner else None

    # ---------------------------------------------------------------- entry
    def parse(self, key, html):
        # the OUTERMOST span.entry -- the one inside div.at-link is popup content
        outer = None
        for m in re.finditer(r'<(\w+)[^>]*\bclass="([^"]*)"[^>]*>', html, re.I):
            if "entry" in m.group(2).split():
                outer = self._balanced(html, m.start())
                break

        # Shape B: a bare collocation-example entry with no span.entry wrapper
        # at all -- <span class="colloexa"><span class="collo">WORD</span>
        # <span class="example">...</span></span>. 1,626 of the first 8,000
        # records are of this shape and were all dropped for want of an entryhead.
        if outer is None:
            return self._parse_colloexa(key, html)
        head = self._cls_inner(outer, "entryhead")
        if head is None:
            # No entryhead, but there may still be senses. Only divert to the
            # colloexa shape when a colloexa is actually present; otherwise fall
            # through and use the record key as the headword. Returning None here
            # dropped ~400 entries that previously parsed.
            ce = self._cls_inner(outer, "colloexa")
            if ce is not None and self._cls_inner(outer, "sense") is None:
                return self._parse_colloexa(key, ce, wrap=False)

        head = self._cls_inner(outer, "entryhead")
        hwd = None
        pron = None
        pos = None
        if head:
            hwd = self._cls_text(head, "hwd")
            pron = self._cls_text(head, "pron")
            pos = self._cls_text(head, "pos")
        if not hwd:
            hwd = key.strip()
        out = [span(hwd, "ld-hwd")]
        if pron:
            out.append(span(pron, "ld-pron"))
        if pos:
            out.append(span(pos, "ld-pos"))

        body = outer
        body = outer
        if head:
            body = outer.replace(head, " ", 1)
        # drop the popup block entirely -- it duplicates the collocation content
        body = re.sub(r'<div[^>]*class="[^"]*\bat-link\b[^"]*"[^>]*>.*?</div>',
                      " ", body, flags=re.S | re.I)
        n = 0
        for sm in re.finditer(
                r'<(\w+)[^>]*\bclass="([^"]*)"[^>]*>', body, re.I):
            if "sense" not in sm.group(2).split():
                continue
            n += 1
            self._sense(self._balanced(body, sm.start()), out, n)

        for cm in re.finditer(
                r'<(\w+)[^>]*\bclass="([^"]*)"[^>]*>', body, re.I):
            if "collocate" not in cm.group(2).split():
                continue
            self._collo(self._balanced(body, cm.start()), out)

        for pm in re.finditer(
                r'<(\w+)[^>]*\bclass="([^"]*)"[^>]*>', body, re.I):
            if "phrase" not in pm.group(2).split():
                continue
            t = self._cls_text(self._balanced(body, pm.start()), "phrasetext") \
                or strip_tags(self._balanced(body, pm.start()))
            if t:
                out.append(div(t, "ld-phrase"))

        # A headword alone is still a usable entry (a cross-reference stub), so
        # only reject when there is nothing but the headword.
        if len(out) < 2:
            return None
        return div(out, "ld-entry")

    def _parse_colloexa(self, key, html, wrap=True):
        """A bare collocation-example entry: WORD + one or more examples."""
        h = self._cls_text(html, "collo") or key.strip()
        out = [span(h, "ld-hwd")]
        for em in re.finditer(
                r'<(\w+)[^>]*\bclass="([^"]*)"[^>]*>', html, re.I):
            if "example" not in em.group(2).split():
                continue
            t = strip_tags(self._balanced(html, em.start()))
            if t:
                out.append(div(t, "ld-ex"))
        if len(out) < 2:
            return None
        return div(out, "ld-entry")

    def _sense(self, s, out, n):
        parts = [span(str(n), "ld-snum")]
        d = self._cls_text(s, "def")
        if d:
            parts.append(span(d, "ld-def"))
        eg = self._cls_inner(s, "example")
        if eg:
            en = strip_tags(eg)
            if en:
                parts.append(div(en, "ld-ex"))
        if len(parts) > 1:
            out.append(div(parts, "ld-sense"))

    def _collo(self, c, out):
        h = self._cls_text(c, "colloc")
        parts = []
        if h:
            parts.append(span(h, "ld-collo-h"))
        cont = self._cls_inner(c, "content")
        if cont:
            en = strip_tags(cont)
            if en:
                parts.append(div(en, "ld-collo-ex"))
        if parts:
            out.append(div(parts, "ld-collo"))


def iter_records(path):
    from mdict_utils.reader import MDX
    m = MDX(path)
    for key, val in m.items():
        k = key.decode("utf-8", "replace") if isinstance(key, bytes) else str(key)
        b = val if isinstance(val, bytes) else str(val).encode()
        yield k, b.decode("utf-8", "replace")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-i", required=True)
    ap.add_argument("-o", required=True)
    ap.add_argument("--revision", default="2026.10.09")
    ap.add_argument("--limit", type=int, default=None)
    args = ap.parse_args()

    p = Parser()
    rows = []
    seq = 0
    n = 0
    skipped = 0
    for key, html in iter_records(args.i):
        n += 1
        if args.limit and n > args.limit:
            break
        if html.lstrip().startswith("@@@LINK="):
            skipped += 1
            continue
        try:
            content = p.parse(key, html)
        except Exception:
            content = None
        if content is None:
            skipped += 1
            continue
        rows.append([key.strip(), "", "", "", 10,
                     [{"type": "structured-content", "content": content}],
                     seq, ""])
        seq += 1

    print(f"scanned {n:,} records, {len(rows):,} entries, {skipped:,} skipped")
    os.makedirs(args.o, exist_ok=True)
    idx = {"title": "Longman Dictionary of Contemporary English 6th (En-En)",
           "format": 3, "revision": args.revision, "sequenced": True,
           "sourceLanguage": "en", "targetLanguage": "en"}
    css = generate_css()
    batch = 10000
    for i in range(0, len(rows), batch):
        chunk = rows[i:i + batch]
        name = f"term_bank_{i // batch + 1}.json"
        with io.open(os.path.join(args.o, name), "w", encoding="utf-8") as f:
            f.write(json.dumps(chunk, ensure_ascii=False, separators=(",", ":")))
        print(f"   wrote {name} ({len(chunk):,} rows)")
    with io.open(os.path.join(args.o, "index.json"), "w", encoding="utf-8") as f:
        f.write(json.dumps(idx, ensure_ascii=False, indent=2))
    with io.open(os.path.join(args.o, "styles.css"), "w", encoding="utf-8") as f:
        f.write(css)
    with io.open(os.path.join(args.o, "tag_bank_1.json"), "w", encoding="utf-8") as f:
        f.write("[]")
    print(f"done: {len(rows):,} rows")


if __name__ == "__main__":
    main()
