"""Convert LDOCE6_New (Longman 6th, English-English) to Yomitan.

A SEPARATE converter from ldoce2yomitan.py on purpose: the user asked that the
LDOCE5++ pipeline not be disturbed, and the two markups share nothing anyway.
It reuses the same format-3 output contract.

Verified structure (converter/_l6_ease.py, _l6_skeleton):

    span.entry                          <- the OUTERMOST one; a nested span.entry
      span.entryhead                      inside div.at-link is popup content and
        span.hwd                          must not be mistaken for the entry
        span.hyphenation
        span.proncodes > span.pron        the pronunciation
        span.pos                          the part of speech
        a.bre_snd / a.ame_snd             audio links (sound://)
        span.buttons
          span.popup-button
          div.at-link                     POPUP: collocation details
            span.entry  (nested)
              span.popheader.popcollo
              span.collocate
                span.expandable > span.arrow + span.colloc.collo
                div.content > span.example
      span.sense ...                      the senses
      span.phrase / span.phrasetext       phrasal entries

212 distinct classes; the names are readable. Hazards are few (5 inline styles,
16 onclick, 1 script in the sampled entry).

This build is ENGLISH-ENGLISH: no Chinese is emitted at all.
"""
import argparse
import io
import json
import os
import re
import sys
import zipfile
from collections import Counter

SC_WHITELIST = {
    "textAlign", "fontWeight", "fontSize", "color", "backgroundColor",
    "margin", "marginTop", "marginBottom", "marginLeft", "marginRight",
    "padding", "paddingTop", "paddingBottom", "paddingLeft", "paddingRight",
    "textDecoration", "textDecorationLine", "listStyleType", "verticalAlign",
    "clipPath", "wordBreak", "whiteSpace", "cursor", "fontStyle", "textShadow",
}


def sc(tag, content, cls=None, **kw):
    d = {}
    if cls:
        d["class"] = cls
    if kw:
        d["style"] = {k: v for k, v in kw.items() if k in SC_WHITELIST}
    node = {"tag": tag}
    if d:
        node["data"] = d
    if content is not None:
        node["content"] = content
    return node


def span(content, cls=None, **kw):
    return sc("span", content, cls, **kw)


def div(content, cls=None, **kw):
    return sc("div", content, cls, **kw)


def strip_tags(s):
    s = re.sub(r"<script\b[^>]*>.*?</script>", " ", s, flags=re.S | re.I)
    s = re.sub(r"<style\b[^>]*>.*?</style>", " ", s, flags=re.S | re.I)
    s = re.sub(r"<[^>]+>", " ", s)
    return re.sub(r"\s+", " ", s).strip()


